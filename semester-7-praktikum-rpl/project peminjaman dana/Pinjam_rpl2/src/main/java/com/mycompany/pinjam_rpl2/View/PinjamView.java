    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        JTextField idField = new JTextField(5);

        JPanel panel = new JPanel();
        panel.add(new JLabel("Masukkan ID yang ingin dihapus:"));
        panel.add(idField);

        int result = JOptionPane.showConfirmDialog(null, panel,
                "Hapus Pinjaman", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);

        if (result == JOptionPane.OK_OPTION) {
            try {
                int id = Integer.parseInt(idField.getText());
                controller.deletePinjam(id);
                JOptionPane.showMessageDialog(null, "Data berhasil dihapus.");

                loadPinjamTable();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "ID harus berupa angka.");
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        try {
            int selectedRow = jTable1.getSelectedRow();
            if (selectedRow == -1) {
                JOptionPane.showMessageDialog(null, "Pilih data dulu!");
                return;
            }

            int id = (int) jTable1.getValueAt(selectedRow, 0);
            String newStatus = JOptionPane.showInputDialog(null, "Masukkan status baru (Diproses/Disetujui/Ditolak)");

            controller.updateStatus(id, newStatus);

            JOptionPane.showMessageDialog(null, "Status berhasil diperbarui!");
            loadPinjamTable();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal update status!");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed


