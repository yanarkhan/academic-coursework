    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        try {
            String nama = namaField.getText();
            double jumlah = Double.parseDouble(jumlahField.getText());
            double bunga = Double.parseDouble(bungaField.getText());
            int waktu = Integer.parseInt(waktuField.getText());
            String status = statusField.getSelectedItem().toString();

            ModelPinjam pinjam = new ModelPinjam(0, nama, jumlah, bunga, waktu, status);

            controller.addPinjam(pinjam);
            JOptionPane.showMessageDialog(null, "Data berhasil disimpan!");

            loadPinjamTable();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Input tidak valid!");
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

